from bank_data.analysis.evidence import FLAT_PATTERN_RATIO, SEGMENT_DIMENSIONS, WEEKDAYS
from bank_data.analysis.labeling import PENDING

Result = dict[str, Any]
NOT_DEFINED = "not defined"


def pct(value: float | None, digits: int = 1) -> str:
    return NOT_DEFINED if value is None else f"{100.0 * value:.{digits}f}%"


def num(value: float | int | None, digits: int = 0) -> str:
    if value is None:
        return NOT_DEFINED
    return f"{value:,.{digits}f}"


def money(value: float | str | None, currency: str) -> str:
    if isinstance(value, str):
        return value
    if value is None:
        return NOT_DEFINED
    return f"{value:,.2f} {currency}" if abs(value) < 1_000 else f"{value:,.0f} {currency}"


def interval_pct(item: Result) -> str:
    if item.get("estimate") is None:
        return NOT_DEFINED
    return f"{pct(item['estimate'])} ({pct(item['low'])} to {pct(item['high'])})"


def interval_num(item: Result, digits: int = 1) -> str:
    if item.get("estimate") is None:
        return NOT_DEFINED
    return f"{num(item['estimate'], digits)} ({num(item['low'], digits)} to {num(item['high'], digits)})"


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return lines


def _mix(rows: list[list[Any]], limit: int = 6) -> str:
    return ", ".join(f"{key} {pct(share)}" for key, _count, share in rows[:limit]) or NOT_DEFINED


def header(meta: Result, title: str) -> list[str]:
    return [
        f"# {title}",
        "",
        f"Generated by `make analysis` at {meta['generated_at']} from commit `{meta['git_sha']}`. "
        f"Source: `{meta['source']}` ({meta['source_description']}); delivery `{meta['dataset_version']}`; "
        f"contacts from {meta['first_day']} to {meta['last_day']}. Pre-registration version "
        f"{meta['preregistration_version']}. Do not edit by hand.",
        "",
    ]


