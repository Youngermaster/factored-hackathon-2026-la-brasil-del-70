def _hour_text(patterns: Result) -> str:
    ratio = patterns["hour_peak_to_trough"]
    hours = patterns["hour_of_day"]
    if ratio is None or not any(hours):
        return "hour of day not defined"
    peak = max(range(24), key=lambda hour: hours[hour])
    if ratio < FLAT_PATTERN_RATIO:
        return f"flat across the local hours of the day (peak to trough {num(ratio, 2)}, no intraday peak)"
    return f"peak local hour {peak} (peak to trough {num(ratio, 2)})"


def _weekday_text(patterns: Result) -> str:
    ratio = patterns["weekday_peak_to_trough"]
    days = patterns["weekday"]
    if ratio is None or not any(days):
        return "day of week not defined"
    peak, trough = max(range(7), key=lambda day: days[day]), min(range(7), key=lambda day: days[day])
    weekend = (days[5] + days[6]) / 2
    weekday = sum(days[:5]) / 5
    return (
        f"busiest weekday {WEEKDAYS[peak]}, quietest {WEEKDAYS[trough]} (peak to trough {num(ratio, 2)}; a weekend day "
        f"carries {pct(weekend / weekday if weekday else None)} of a weekday's volume)"
    )


def _patterns_section(results: Result) -> list[str]:
    lines = [
        "## Demand patterns",
        "",
        "Hours and weekdays are local to the customer's country (fixed offsets: Mexico UTC-6, Colombia UTC-5, "
        "Argentina UTC-3), from UTC timestamps. The hour-of-day curves are flat in every workflow (a generator "
        "property: no intraday staffing signal exists in this data); the weekly pattern is real, with weekend days "
        "at about half a weekday's volume.",
        "",
        "![Interactions by local hour of day](figures/hour-of-day.png)",
        "",
        "![Interactions by local day of week](figures/day-of-week.png)",
        "",
        "Spike days: daily contacts (interactions plus complaints) above the trailing 28-day median by more "
        "than the pre-registered robust z-score.",
        "",
    ]
    rows = []
    for workflow in WORKFLOWS:
        patterns = results["patterns"]["workflows"][workflow]
        top = "; ".join(
            f"{spike['day']} ({num(spike['volume'])} against {num(spike['baseline'], 0)}, "
            f"z {num(spike['robust_z'], 1)})"
            for spike in patterns["top_spikes"]
        )
        rows.append([f"`{workflow}`", num(patterns["days"]), num(patterns["spikes"]), top or "none"])
    lines += _table(["Workflow", "Days", "Spike days", "Largest spikes"], rows)
    lines += [""]
    return lines


def _lag_section(results: Result) -> list[str]:
    lag = results["lag"]
    error, baseline = lag["error"], lag["baseline"]
    lines = [
        "## Digital errors followed by a contact",
        "",
        f"For digital events of identified customers: the share followed by a contact-center interaction of the "
        f"same customer within {lag['window_hours']} hours, for `error` events against a deterministic 5% hash "
        "sample of all other events. **This is an association, not a causal effect**: customers who use digital "
        "channels more also call more, and the synthetic generator may not link the two at all.",
        "",
    ]
    lines += _table(
        ["Events", "Count", "Contact within the window (95% interval)"],
        [
            ["Error events", num(error["events"]), interval_pct(error["contact_within_window"])],
            ["Other events (5% sample)", num(baseline["events"]), interval_pct(baseline["contact_within_window"])],
        ],
    )
    lines += [
        "",
        f"Rate ratio (error over other): {num(lag['rate_ratio'], 2)}. Workflow of the contact after an error: "
        f"{_mix(error['contact_workflows'])}.",
        "",
        "![Contact after a digital event](figures/error-contact-lag.png)",
        "",
    ]
    lines += _table(
        ["Page of the error", "Error events", "Contact within the window"],
        [[str(page), num(count), pct(share, 2)] for page, count, share in lag["error_pages"][:10]],
    )
    lines += [""]
    return lines


def _automatable_section(results: Result) -> list[str]:
    transcripts = results["transcripts"]
    facts = transcripts["facts"]
    lines = [
        "## Automatable share and the labeling task",
        "",
        "The automatable share is a human labeling task ([`labeling-protocol.md`](labeling-protocol.md)). "
        "Until at least the pre-registered number of adjudicated items per workflow match that workflow, every "
        "score uses the structured proxy (resolved at first contact, not escalated, no follow-up), labeled as a proxy.",
        "",
    ]
    rows = []
    for workflow in WORKFLOWS:
        labels = results["labels"]["workflows"][workflow]
        rows.append(
            [
                f"`{workflow}`",
                num(labels["items"]),
                num(labels["adjudicated"]),
                num(labels["matching"]),
                num(labels["kappa_resolvable"], 2) if labels["kappa_resolvable"] is not None else NOT_DEFINED,
                labels["status"],
                pct(labels["share"]),
            ]
        )
    lines += _table(
        ["Workflow", "Items", "Adjudicated", "Matching the workflow", "Kappa", "Status", "Labeled share"], rows
    )
    export = results.get("labeling_export")
    if export:
        lines += [
            "",
            f"Labeling file: `{export['path']}` ({export['status']}; {num(export['items'])} items: "
            + ", ".join(f"{workflow} {num(count)}" for workflow, count in export["per_workflow"].items())
            + "). Machine pre-labels (review status `pending`, never used as labels) are in "
            f"`{export['prelabel_path']}`:",
            "",
        ]
        lines += _table(
            ["Stratum", "Pre-label topic", "Matches stratum", "Items"],
            [
                [f"`{stratum}`", topic, matches, num(count)]
                for stratum, topic, matches, count in export["prelabel_summary"]
            ],
        )
    lines += [
        "",
        "### Transcripts carry no workflow signal",
        "",
        f"{num(facts['transcripts'])} served transcripts hold {num(facts['distinct_customer_texts'])} distinct "
        "customer "
        f"texts; `detected_intents` has {num(facts['distinct_detected_intents'])} distinct value(s) "
        f"({', '.join(f'{value} {num(count)}' for value, count in transcripts['detected_intents'])}); `main_topics` "
        f"equals `contact_reason` on {num(facts['main_topics_equal_contact_reason'])} transcripts (a copy of the "
        "label, not an independent signal). The balance question in the customer text does not depend on the "
        "contact reason (Cramer's V "
        f"{num(transcripts['cramers_v_reason_by_opening'], 3)}; 0 means independence):",
        "",
    ]
    lines += _table(
        ["Contact reason", "Balance sentence of the customer text", "Transcripts"],
        [[reason, opening, num(count)] for reason, opening, count in transcripts["openings"]],
    )
    lines += [
        "",
        "Consequence: a human label on these texts measures a balance question, whatever the workflow stratum. The "
        "protocol therefore records whether the text matches the workflow, and only matching items count. For "
        "`card_support`, `dispute`, and `credit` the labels are expected to confirm that transcripts cannot measure "
        "the automatable share, and phase 10 needs team-authored or paraphrased utterances, labeled as such, to train "
        "and evaluate the router.",
        "",
    ]
    return lines


def _cost_section(results: Result) -> list[str]:
    costs = results["costs"]
    currency = costs["currency"]
    lines = [
        "## Cost baseline (projected, from assumptions)",
        "",
        "Handle cost = handled minutes (`duration_seconds`) times the assumed loaded cost per minute of the "
        "customer's country times the after-call-work factor. Contacts without a duration are costed at the "
        "workflow mean. Complaint back-office handling is not in the data and is excluded. The addressable cost is "
        "the last 365 days of handle cost times the automatable share: the label-based figure waits for human "
        "labels; the ceiling assumes a share of 100%; the proxy figure uses the structured proxy. None of these is "
        f"a measured saving. Window end: {costs['annual_window_end']}.",
        "",
    ]
    rows = []
    for workflow in WORKFLOWS:
        item = costs["workflows"][workflow]
        base = item["scenarios"]["1"]
        rows.append(
            [
                f"`{workflow}`",
                num(item["contacts"]),
                num(item["mean_handle_minutes"], 2),
                money(base["cost_per_contact"], currency),
                money(base["cost_per_resolved_contact"], currency),
                money(base["total_cost"], currency),
                money(base["annual_handle_cost"], currency),
                money(base["addressable_label_based"], currency),
                money(base["addressable_proxy"], currency),
            ]
        )
    lines += _table(
        [
            "Workflow",
            "Contacts",
            "Mean handled minutes",
            "Cost per contact",
            "Cost per resolved contact",
            "Total, full period",
            "Handle cost, last 365 days",
            "Addressable, label-based",
            "Addressable, proxy",
        ],
        rows,
    )
    lines += ["", "Sensitivity of the cost per resolved contact to the assumed loaded cost:", ""]
    multipliers = list(costs["workflows"][WORKFLOWS[0]]["scenarios"])
    lines += _table(
        ["Workflow", *[f"{multiplier} x" for multiplier in multipliers]],
        [
            [f"`{workflow}`"]
            + [
                money(costs["workflows"][workflow]["scenarios"][m]["cost_per_resolved_contact"], currency)
                for m in multipliers
            ]
            for workflow in WORKFLOWS
        ],
    )
    lines += [""]
    return lines


